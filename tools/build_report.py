def make_pdf(pages):
    font_dir = Path("C:/Windows/Fonts")
    if font_dir.exists():
        normal, bold = font_dir / "times.ttf", font_dir / "timesbd.ttf"
    else:
        font_dir = Path("/usr/share/fonts/truetype/dejavu")
        normal, bold = font_dir / "DejaVuSerif.ttf", font_dir / "DejaVuSerif-Bold.ttf"
    pdfmetrics.registerFont(TTFont("Report", str(normal)))
    pdfmetrics.registerFont(TTFont("ReportBold", str(bold)))
    styles = {
        "p": ParagraphStyle("body", fontName="Report", fontSize=12, leading=16, spaceAfter=10, alignment=TA_JUSTIFY),
        "h": ParagraphStyle("heading", fontName="ReportBold", fontSize=14, leading=18, spaceBefore=9, spaceAfter=12),
        "title": ParagraphStyle("title", fontName="ReportBold", fontSize=21, leading=27, spaceAfter=22, alignment=TA_CENTER),
        "subtitle": ParagraphStyle("subtitle", fontName="ReportBold", fontSize=16, leading=22, spaceAfter=23, alignment=TA_CENTER),
        "cell": ParagraphStyle("cell", fontName="Report", fontSize=9, leading=12),
        "link": ParagraphStyle("link", fontName="Report", fontSize=11, leading=15, spaceAfter=11),
    }
    story = []
    available = 170 * mm

    def cell(value):
        return Paragraph(escape(str(value)), styles["cell"])

    def table(rows, widths):
        obj = Table([[cell(v) for v in row] for row in rows], colWidths=widths, repeatRows=1, hAlign="LEFT")
        obj.setStyle(TableStyle([
            ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#E8ECF0")),
            ("GRID", (0, 0), (-1, -1), 0.4, colors.HexColor("#A0A5AA")),
            ("VALIGN", (0, 0), (-1, -1), "TOP"),
            ("LEFTPADDING", (0, 0), (-1, -1), 5), ("RIGHTPADDING", (0, 0), (-1, -1), 5),
            ("TOPPADDING", (0, 0), (-1, -1), 6), ("BOTTOMPADDING", (0, 0), (-1, -1), 6),
        ]))
        return obj

    for index, page in enumerate(pages):
        if index:
            story.append(PageBreak())
        for kind, content in page:
            if kind in styles and kind != "link":
                story.append(Paragraph(escape(content).replace("\n", "<br/>"), styles[kind]))
            elif kind == "image":
                story += [Image(str(ROOT / content), width=available, height=available * 720 / 1280), Spacer(1, 10)]
            elif kind == "link":
                label, url = content
                story.append(Paragraph(f'<link href="{escape(url, quote=True)}" color="#204B76">{escape(label)}</link>', styles["link"]))
            elif kind == "rules":
                rows = [["Правило", "Приор.", "Условие", "Действие"]] + list(content)
                story += [table(rows, [35 * mm, 14 * mm, 64 * mm, 57 * mm]), Spacer(1, 12)]
            elif kind == "results":
                rows = [["№", "Сценарий", "Шаги", "Правила", "Итог"]]
                rows += [[i + 1, data["name"], len(records), sum(len(r["fired"]) for r in records), "OK"]
                         for i, (_, data, records) in enumerate(content)]
                story += [table(rows, [10 * mm, 105 * mm, 18 * mm, 21 * mm, 16 * mm]), Spacer(1, 12)]
    doc = SimpleDocTemplate(str(ROOT / "docs/report.pdf"), pagesize=A4,
                            rightMargin=20 * mm, leftMargin=20 * mm, topMargin=20 * mm, bottomMargin=20 * mm,
                            title="Лабораторная работа 3 — Печенов В. В.", author="Печенов В. В.")

    def footer(canvas, doc):
        canvas.setFont("Report", 10)
        canvas.drawCentredString(A4[0] / 2, 11 * mm, str(doc.page))

    doc.build(story, onFirstPage=footer, onLaterPages=footer)


